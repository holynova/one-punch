import type { RepoTextFile, Repository } from "../repo/types";
import { repoParentPath, validateRepoPath } from "../repo/validate-path";
import { utf8ToBase64, wrapBase64 } from "./base64";
import { uniqueDelimiter } from "./delimiter";

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, "'\\''")}'`;
}

function shellPath(path: string): string {
  if (path.length === 0) return '"$ROOT"';
  validateRepoPath(path);
  return `"$ROOT"/${shellQuote(path)}`;
}

function commentSafe(value: string): string {
  return value.replace(/[\r\n]/g, " ");
}

function sortedFiles(files: RepoTextFile[]): RepoTextFile[] {
  return [...files].sort((left, right) => left.path.localeCompare(right.path));
}

function appendTextFile(chunks: string[], file: RepoTextFile): void {
  validateRepoPath(file.path);
  const target = shellPath(file.path);
  chunks.push(`mkdir -p -- ${shellPath(repoParentPath(file.path))}\n`);

  if (file.content.length === 0) {
    chunks.push(`: > ${target}\n\n`);
    return;
  }

  // A heredoc preserves ordinary source text without shell expansion. Its
  // delimiter must start on a new line, so files without a final newline use
  // the portable base64 path to remain byte-for-byte exact.
  const canUseHeredoc = file.content.endsWith("\n") && !file.content.includes("\0");
  if (canUseHeredoc) {
    const delimiter = uniqueDelimiter(file.content, "__R2S_TEXT_");
    chunks.push(`cat > ${target} <<'${delimiter}'\n`);
    chunks.push(file.content);
    chunks.push(`${delimiter}\n\n`);
    return;
  }

  const delimiter = uniqueDelimiter(file.content, "__R2S_B64_");
  const encoded = wrapBase64(utf8ToBase64(file.content));
  chunks.push(
    `if base64 -d > ${target} <<'${delimiter}'\n${encoded}\n${delimiter}\nthen\n  :\nelse\n  base64 -D > ${target} <<'${delimiter}'\n${encoded}\n${delimiter}\nfi\n\n`
  );
}

export function generateSetupScript(repository: Repository): string {
  const chunks: string[] = [
    "#!/usr/bin/env bash\n",
    "set -eu\n",
    "\n",
    "# Generated by Repo2Script (browser-only GitHub HTML exporter).\n",
    `# Source: ${commentSafe(repository.sourceUrl)}\n`,
    `# Ref: ${commentSafe(repository.ref)}\n`,
    `# Text files: ${repository.files.length}\n`,
    `# Unsupported: ${repository.unsupported.length}\n`,
    "\n",
    'ROOT="${1:-.}"\n',
    'mkdir -p -- "$ROOT"\n\n'
  ];

  for (const file of sortedFiles(repository.files)) appendTextFile(chunks, file);

  if (repository.unsupported.length > 0) {
    chunks.push("# Unsupported files were intentionally not written:\n");
    for (const item of repository.unsupported) {
      chunks.push(`# - ${commentSafe(item.path)}: ${commentSafe(item.reason)}\n`);
    }
    chunks.push("\n");
  }

  if (repository.warnings.length > 0) {
    chunks.push("# Crawl warnings:\n");
    for (const warning of repository.warnings) {
      chunks.push(`# - ${commentSafe(warning)}\n`);
    }
    chunks.push("\n");
  }

  return chunks.join("");
}

export { shellQuote };
